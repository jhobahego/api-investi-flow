"""Retrieval-Augmented Generation (RAG) over document chunks.

Chunks live in ``document_chunks`` with a 768-dimension embedding generated by
Google GenAI (``gemini-embedding-001``). On PostgreSQL retrieval uses pgvector's
cosine distance; on SQLite (tests, local) it computes cosine similarity in
Python so the same API works without the ``vector`` extension.
"""

import logging
import math
import os
import re
from typing import Any, Optional

from fastapi import HTTPException
from google import genai
from google.genai import types
from sqlalchemy import Float, literal, select
from sqlalchemy.orm import Session

from app.core.config import settings
from app.core.gemini_guard import truncate_context
from app.database import SessionLocal
from app.models.attachment import Attachment, FileType, IndexingStatus
from app.models.document_chunk import EMBEDDING_DIMENSION, DocumentChunk, EmbeddingType
from app.models.phase import Phase
from app.models.project import Project
from app.models.task import Task

logger = logging.getLogger(__name__)

DEFAULT_CHUNK_SIZE = 900
DEFAULT_CHUNK_OVERLAP = 120
DEFAULT_TOP_K = 5
MAX_EMBED_BATCH = 50
MAX_TASK_TEXT_CHARS = 1_000_000
RAG_CONTEXT_MAX_CHARS = 8000
DEFAULT_EMBEDDING_MODEL = "gemini-embedding-001"

_WORD_RE = re.compile(r"\w+", re.UNICODE)
_PARAGRAPH_RE = re.compile(r"\n\s*\n")
_DISABLED_VALUES = ("false", "0", "no", "off")


class RAGServiceError(Exception):
    """Raised when chunk embedding or indexing cannot be completed."""


class RAGService:
    """Chunking, embedding, indexing and retrieval for document RAG."""

    def __init__(self) -> None:
        self._client: Any | None = None

    # ------------------------------------------------------------------ client
    def _get_client(self) -> Any | None:
        if self._client is not None:
            return self._client
        api_key = settings.get_google_ai_api_key()
        if not api_key:
            return None
        self._client = genai.Client(api_key=api_key)
        return self._client

    # --------------------------------------------------------------- embedding
    def embed_texts(self, texts: list[str]) -> list[list[float]]:
        """Embed texts in batches. Raises RAGServiceError without a client."""
        cleaned = [text for text in texts if text and text.strip()]
        if not cleaned:
            return []

        client = self._get_client()
        if client is None:
            raise RAGServiceError(
                "GOOGLE_AI_API_KEY no está configurada para generar embeddings"
            )

        vectors: list[list[float]] = []
        for start in range(0, len(cleaned), MAX_EMBED_BATCH):
            batch = cleaned[start : start + MAX_EMBED_BATCH]
            response = self._embed_batch(client, batch)
            for embedding in response.embeddings or []:
                values = [float(value) for value in embedding.values]
                if len(values) != EMBEDDING_DIMENSION:
                    raise RAGServiceError(
                        "Dimensión de embedding inválida: "
                        f"esperada {EMBEDDING_DIMENSION}, recibida {len(values)}"
                    )
                vectors.append(values)
        return vectors

    def _embed_batch(self, client: Any, batch: list[str]) -> Any:
        model_name = settings.AI_MODEL_EMBEDDING or DEFAULT_EMBEDDING_MODEL
        config = types.EmbedContentConfig(output_dimensionality=EMBEDDING_DIMENSION)
        try:
            return client.models.embed_content(
                model=model_name,
                contents=batch,
                config=config,
            )
        except (TypeError, ValueError) as exc:
            if "output_dimensionality" not in str(exc):
                raise
            logger.warning(
                "output_dimensionality no soportado, reintentando sin config: %s",
                exc,
            )
            return client.models.embed_content(model=model_name, contents=batch)

    # ---------------------------------------------------------------- chunking
    def chunk_text(
        self,
        text: str,
        chunk_size: int = DEFAULT_CHUNK_SIZE,
        overlap: int = DEFAULT_CHUNK_OVERLAP,
    ) -> list[str]:
        """Split text into heading/paragraph-aware chunks with overlap."""
        if not text:
            return []

        normalized = text.replace("\r\n", "\n").replace("\r", "\n").strip()
        if not normalized:
            return []

        safe_chunk_size = chunk_size if chunk_size > 0 else DEFAULT_CHUNK_SIZE
        safe_overlap = max(0, min(overlap, safe_chunk_size // 2))

        paragraphs = [part.strip() for part in _PARAGRAPH_RE.split(normalized)]
        paragraphs = [part for part in paragraphs if part]
        if not paragraphs:
            return []

        chunks: list[str] = []
        current = ""

        for paragraph in paragraphs:
            if len(paragraph) > safe_chunk_size:
                if current:
                    chunks.append(current.strip())
                    current = ""
                chunks.extend(
                    self._split_oversized(paragraph, safe_chunk_size, safe_overlap)
                )
                continue

            if not current:
                current = paragraph
                continue

            if len(current) + 2 + len(paragraph) <= safe_chunk_size:
                current = f"{current}\n\n{paragraph}"
                continue

            chunks.append(current.strip())
            tail = self._overlap_tail(current, safe_overlap)
            candidate = f"{tail}\n\n{paragraph}" if tail else paragraph
            current = candidate if len(candidate) <= safe_chunk_size else paragraph

        if current.strip():
            chunks.append(current.strip())

        deduped: list[str] = []
        for chunk in chunks:
            cleaned = chunk.strip()
            if not cleaned:
                continue
            if deduped and deduped[-1] == cleaned:
                continue
            deduped.append(cleaned)
        return deduped

    def _split_oversized(
        self, paragraph: str, chunk_size: int, overlap: int
    ) -> list[str]:
        slices: list[str] = []
        start = 0
        total = len(paragraph)

        while start < total:
            end = min(start + chunk_size, total)
            piece = paragraph[start:end]
            if end < total and " " in piece:
                boundary = piece.rfind(" ")
                if boundary > chunk_size // 2:
                    end = start + boundary
                    piece = paragraph[start:end]
            cleaned = piece.strip()
            if cleaned:
                slices.append(cleaned)
            if end >= total:
                break
            start = max(end - overlap, start + 1)

        return slices

    def _overlap_tail(self, chunk: str, overlap: int) -> str:
        if overlap <= 0 or not chunk:
            return ""
        tail = chunk[-overlap:]
        first_space = tail.find(" ")
        if first_space != -1 and first_space < len(tail) - 1:
            tail = tail[first_space + 1 :]
        return tail.strip()

    # ---------------------------------------------------------------- extract
    def extract_text(self, attachment: Attachment) -> str:
        """Extract plain text from a DOCX/PDF/TXT/MD attachment."""
        file_type = attachment.file_type
        type_name = (
            file_type.value
            if isinstance(file_type, FileType)
            else str(file_type).lower()
        )
        file_path = str(attachment.file_path)

        try:
            if type_name == FileType.DOCX.value:
                # Legacy binary .doc is accepted by the upload layer but
                # python-docx cannot parse it. Skip it instead of embedding an
                # error string as document content.
                if str(attachment.file_name).lower().endswith(".doc"):
                    logger.warning(
                        "Adjunto %s es un .doc legado; se omite del indexado RAG",
                        attachment.id,
                    )
                    return ""
                return self._extract_docx(file_path)
            if type_name == FileType.PDF.value:
                from app.services.document_extraction_service import (
                    document_extraction_service,
                )

                text = document_extraction_service.extract_pdf_to_text(file_path)
                if text.startswith("Error"):
                    # extract_pdf_to_text returns error strings instead of
                    # raising; do not index those as document content.
                    raise RAGServiceError(text)
                return text
            if type_name in ("txt", "md"):
                with open(file_path, "r", encoding="utf-8", errors="ignore") as handle:
                    return handle.read()
        except RAGServiceError:
            raise
        except Exception as exc:
            logger.exception("Error extrayendo texto del adjunto %s", attachment.id)
            raise RAGServiceError(
                f"No se pudo extraer texto del adjunto {attachment.id}"
            ) from exc
        return ""

    @staticmethod
    def _extract_docx(file_path: str) -> str:
        from docx import Document

        document = Document(file_path)
        parts = [
            paragraph.text.strip()
            for paragraph in document.paragraphs
            if paragraph.text and paragraph.text.strip()
        ]
        for table in document.tables:
            for row in table.rows:
                for cell in row.cells:
                    if cell.text and cell.text.strip():
                        parts.append(cell.text.strip())
        return "\n".join(parts)

    # ---------------------------------------------------------- project lookup
    def resolve_project_id(self, db: Session, attachment: Attachment) -> int | None:
        """Resolve the project that owns an attachment through its parent."""
        if attachment.project_id is not None:
            return int(attachment.project_id)
        if attachment.phase_id is not None:
            phase = db.get(Phase, attachment.phase_id)
            return int(phase.project_id) if phase is not None else None
        if attachment.task_id is not None:
            task = db.get(Task, attachment.task_id)
            if task is None:
                return None
            phase = db.get(Phase, task.phase_id)
            return int(phase.project_id) if phase is not None else None
        return None

    # --------------------------------------------------------------- indexing
    def index_attachment(self, db: Session, attachment: Attachment) -> int:
        """Extract text from the file and index it. Returns chunk count."""
        text = self.extract_text(attachment)
        return self._index_text(db, attachment, text)

    def index_attachment_text(
        self, db: Session, attachment: Attachment, text: str
    ) -> int:
        """Index already-extracted text without touching the filesystem."""
        return self._index_text(db, attachment, text)

    def _index_text(self, db: Session, attachment: Attachment, text: str) -> int:
        """Chunk, embed and persist text. Returns chunk count."""
        project_id = self.resolve_project_id(db, attachment)
        if project_id is None:
            raise ValueError(
                "No se pudo resolver el proyecto del adjunto "
                f"{attachment.id} para indexarlo"
            )

        chunks = self.chunk_text(text)
        if not chunks:
            self.delete_attachment_chunks(db, attachment.id)
            db.commit()
            return 0

        try:
            embeddings = self.embed_texts(chunks)
        except RAGServiceError:
            logger.exception(
                "Error generando embeddings para adjunto %s", attachment.id
            )
            raise
        except Exception as exc:
            logger.exception(
                "Error inesperado generando embeddings para adjunto %s",
                attachment.id,
            )
            raise RAGServiceError("Error generando embeddings") from exc

        if len(embeddings) != len(chunks):
            raise RAGServiceError(
                "Cantidad de embeddings no coincide con la cantidad de fragmentos"
            )

        self.delete_attachment_chunks(db, attachment.id)
        rows = [
            DocumentChunk(
                attachment_id=attachment.id,
                project_id=project_id,
                chunk_index=index,
                content=content,
                embedding=embedding,
                token_count=max(1, len(content) // 3),
            )
            for index, (content, embedding) in enumerate(zip(chunks, embeddings))
        ]
        db.add_all(rows)
        db.commit()
        return len(rows)

    def _set_indexing_status(
        self, db: Session, attachment_id: int, status: IndexingStatus
    ) -> None:
        """Persist the indexing status of an attachment; no-op if missing."""
        attachment = db.get(Attachment, attachment_id)
        if attachment is None:
            return
        attachment.indexing_status = status.value
        db.commit()

    def _mark_indexing_error_best_effort(self, attachment_id: int) -> None:
        """Best-effort ERROR marking: never raises, never overrides INDEXED."""
        db = SessionLocal()
        try:
            attachment = db.get(Attachment, attachment_id)
            if attachment is None:
                return
            if attachment.indexing_status == IndexingStatus.INDEXED.value:
                return
            self._set_indexing_status(db, attachment_id, IndexingStatus.ERROR)
        except Exception:
            logger.exception(
                "No se pudo marcar el adjunto %s como error de indexación",
                attachment_id,
            )
            try:
                db.rollback()
            except Exception:
                pass
        finally:
            try:
                db.close()
            except Exception:
                pass

    def index_attachment_in_session(self, attachment_id: int) -> int:
        """Celery entry point: index in a fresh session and re-raise failures."""
        db = SessionLocal()
        try:
            attachment = db.get(Attachment, attachment_id)
            if attachment is None:
                return 0
            self._set_indexing_status(db, attachment_id, IndexingStatus.INDEXING)
            count = self.index_attachment(db, attachment)
            self._set_indexing_status(
                db,
                attachment_id,
                IndexingStatus.INDEXED if count > 0 else IndexingStatus.ERROR,
            )
            return count
        except Exception:
            db.rollback()
            try:
                self._set_indexing_status(db, attachment_id, IndexingStatus.ERROR)
            except Exception:
                logger.exception(
                    "No se pudo marcar el adjunto %s como error de indexación",
                    attachment_id,
                )
            raise
        finally:
            db.close()

    def index_attachment_text_in_session(self, attachment_id: int, text: str) -> int:
        """Celery entry point for pre-extracted text; re-raises on failure."""
        db = SessionLocal()
        try:
            attachment = db.get(Attachment, attachment_id)
            if attachment is None:
                return 0
            self._set_indexing_status(db, attachment_id, IndexingStatus.INDEXING)
            count = self.index_attachment_text(db, attachment, text)
            self._set_indexing_status(
                db,
                attachment_id,
                IndexingStatus.INDEXED if count > 0 else IndexingStatus.ERROR,
            )
            return count
        except Exception:
            db.rollback()
            try:
                self._set_indexing_status(db, attachment_id, IndexingStatus.ERROR)
            except Exception:
                logger.exception(
                    "No se pudo marcar el adjunto %s como error de indexación",
                    attachment_id,
                )
            raise
        finally:
            db.close()

    def enqueue_attachment_indexing(self, attachment_id: int) -> bool:
        """Enqueue indexing on Celery. Enqueue failures never fail the request."""
        if not self.indexing_enabled():
            return False
        try:
            from app.tasks.rag_tasks import index_attachment_task

            index_attachment_task.delay(attachment_id)
            return True
        except Exception:
            logger.exception(
                "No se pudo encolar el indexado RAG del adjunto %s", attachment_id
            )
            self._mark_indexing_error_best_effort(attachment_id)
            return False

    def enqueue_attachment_text_indexing(self, attachment: Attachment) -> bool:
        """Extract text in the API and enqueue it with the task payload.

        Sending the text keeps the worker independent from the API's disk. If
        extraction fails, is empty, or the text is too large, fall back to the
        file-based task (which requires a shared disk).
        """
        if not self.indexing_enabled():
            return False
        try:
            text = self.extract_text(attachment)
            if not text.strip():
                logger.warning(
                    "No hay texto extraído para el adjunto %s; no se indexa",
                    attachment.id,
                )
                return False
            if len(text) > MAX_TASK_TEXT_CHARS:
                logger.warning(
                    "Texto del adjunto %s supera %s caracteres; "
                    "se usa la tarea basada en archivo",
                    attachment.id,
                    MAX_TASK_TEXT_CHARS,
                )
                return self.enqueue_attachment_indexing(attachment.id)

            from app.tasks.rag_tasks import index_attachment_text_task

            index_attachment_text_task.delay(attachment.id, text)
            return True
        except Exception:
            logger.exception(
                "No se pudo encolar el indexado RAG (texto) del adjunto %s; "
                "se intenta la tarea basada en archivo",
                attachment.id,
            )
            return self.enqueue_attachment_indexing(attachment.id)

    def index_attachment_background(self, attachment_id: int) -> None:
        """Background wrapper: never raises, opens its own session."""
        if not self.indexing_enabled():
            return

        db = SessionLocal()
        try:
            attachment = db.get(Attachment, attachment_id)
            if attachment is None:
                return
            self._set_indexing_status(db, attachment_id, IndexingStatus.INDEXING)
            count = self.index_attachment(db, attachment)
            self._set_indexing_status(
                db,
                attachment_id,
                IndexingStatus.INDEXED if count > 0 else IndexingStatus.ERROR,
            )
        except Exception:
            db.rollback()
            try:
                self._set_indexing_status(db, attachment_id, IndexingStatus.ERROR)
            except Exception:
                logger.exception(
                    "No se pudo marcar el adjunto %s como error de indexación",
                    attachment_id,
                )
            logger.exception("Error indexando adjunto %s en background", attachment_id)
        finally:
            db.close()

    def indexing_enabled(self) -> bool:
        raw = os.getenv("RAG_INDEXING_ENABLED")
        if raw is not None:
            return raw.strip().lower() not in _DISABLED_VALUES
        return bool(settings.RAG_INDEXING_ENABLED)

    def delete_attachment_chunks(self, db: Session, attachment_id: int) -> int:
        """Delete all chunks of an attachment. Caller is responsible for commit."""
        chunks = list(
            db.execute(
                select(DocumentChunk).where(
                    DocumentChunk.attachment_id == attachment_id
                )
            )
            .scalars()
            .all()
        )
        for chunk in chunks:
            db.delete(chunk)
        db.flush()
        return len(chunks)

    # -------------------------------------------------------------- retrieval
    def retrieve_context(
        self,
        db: Session,
        project_id: int,
        query: str,
        top_k: int = DEFAULT_TOP_K,
        attachment_id: int | None = None,
    ) -> list[dict[str, Any]]:
        """Return the most relevant chunks of a project or one attachment."""
        if not query or not query.strip() or not project_id:
            return []

        try:
            bind = db.get_bind()
            dialect_name = bind.dialect.name if bind is not None else "sqlite"
            if dialect_name == "postgresql":
                return self._retrieve_postgres(
                    db, project_id, query, top_k, attachment_id
                )
            return self._retrieve_python(db, project_id, query, top_k, attachment_id)
        except Exception:
            logger.exception(
                "Error recuperando contexto RAG del proyecto %s", project_id
            )
            return []

    def _load_chunks(
        self,
        db: Session,
        project_id: int,
        only_with_embedding: bool,
        attachment_id: int | None = None,
    ) -> list[DocumentChunk]:
        stmt = select(DocumentChunk).where(DocumentChunk.project_id == project_id)
        if attachment_id is not None:
            stmt = stmt.where(DocumentChunk.attachment_id == attachment_id)
        if only_with_embedding:
            stmt = stmt.where(DocumentChunk.embedding.is_not(None))
        return list(db.execute(stmt).scalars().all())

    def _retrieve_postgres(
        self,
        db: Session,
        project_id: int,
        query: str,
        top_k: int,
        attachment_id: int | None = None,
    ) -> list[dict[str, Any]]:
        try:
            query_vector = self.embed_texts([query])[0]
        except Exception:
            logger.warning("Embedding de consulta falló; usando búsqueda por palabras")
            return self._retrieve_lexical(
                db,
                project_id,
                query,
                top_k,
                self._load_chunks(db, project_id, False, attachment_id),
                attachment_id,
            )

        distance = self._distance_expression(query_vector)
        conditions = [
            DocumentChunk.project_id == project_id,
            DocumentChunk.embedding.is_not(None),
        ]
        if attachment_id is not None:
            conditions.append(DocumentChunk.attachment_id == attachment_id)
        stmt = (
            select(DocumentChunk, distance)
            .where(*conditions)
            .order_by(distance)
            .limit(top_k)
        )
        results: list[dict[str, Any]] = []
        for chunk, raw_distance in db.execute(stmt).all():
            similarity = 1.0 - float(raw_distance) if raw_distance is not None else 0.0
            results.append(self._chunk_to_result(db, chunk, similarity))
        return results

    @staticmethod
    def _distance_expression(query_vector: list[float]) -> Any:
        """Build the pgvector cosine-distance expression with a Float result.

        ``TypeDecorator`` columns do not expose pgvector's ``cosine_distance``
        comparator, so the equivalent ``<=>`` operator is used explicitly. The
        literal is typed with ``EmbeddingType`` so the bind is sent as a vector,
        and ``return_type=Float()`` prevents SQLAlchemy from inheriting the
        embedding column's ``Vector`` type for the scalar distance (which would
        make pgvector's result processor try to parse a float as a vector).
        """
        query_param = literal(query_vector, type_=EmbeddingType())
        return DocumentChunk.embedding.op("<=>", return_type=Float())(
            query_param
        ).label("distance")

    def _retrieve_python(
        self,
        db: Session,
        project_id: int,
        query: str,
        top_k: int,
        attachment_id: int | None = None,
    ) -> list[dict[str, Any]]:
        chunks = self._load_chunks(db, project_id, False, attachment_id)
        if not chunks:
            return []

        query_vector: Optional[list[float]] = None
        try:
            vectors = self.embed_texts([query])
            if vectors:
                query_vector = vectors[0]
        except Exception:
            logger.warning("Embedding de consulta falló; usando puntuación léxica")

        if query_vector is not None:
            scored: list[tuple[float, DocumentChunk]] = []
            for chunk in chunks:
                embedding = chunk.embedding
                if not isinstance(embedding, list) or len(embedding) != len(
                    query_vector
                ):
                    continue
                similarity = self._cosine_similarity(
                    query_vector, [float(value) for value in embedding]
                )
                scored.append((similarity, chunk))
            if scored:
                scored.sort(key=lambda item: item[0], reverse=True)
                return [
                    self._chunk_to_result(db, chunk, similarity)
                    for similarity, chunk in scored[:top_k]
                ]

        return self._retrieve_lexical(
            db, project_id, query, top_k, chunks, attachment_id
        )

    def _retrieve_lexical(
        self,
        db: Session,
        project_id: int,
        query: str,
        top_k: int,
        chunks: list[DocumentChunk],
        attachment_id: int | None = None,
    ) -> list[dict[str, Any]]:
        query_tokens = set(_WORD_RE.findall(query.lower()))
        scored: list[tuple[float, DocumentChunk]] = []
        for chunk in chunks:
            tokens = _WORD_RE.findall(chunk.content.lower())
            if not tokens or not query_tokens:
                scored.append((0.0, chunk))
                continue
            overlap = sum(1 for token in tokens if token in query_tokens)
            scored.append((overlap / float(len(tokens)), chunk))

        scored.sort(key=lambda item: item[0], reverse=True)
        top = scored[:top_k]
        if any(score > 0 for score, _ in top):
            return [self._chunk_to_result(db, chunk, score) for score, chunk in top]

        conditions = [DocumentChunk.project_id == project_id]
        if attachment_id is not None:
            conditions.append(DocumentChunk.attachment_id == attachment_id)
        recent = list(
            db.execute(
                select(DocumentChunk)
                .where(*conditions)
                .order_by(DocumentChunk.created_at.desc(), DocumentChunk.id.desc())
                .limit(top_k)
            )
            .scalars()
            .all()
        )
        return [self._chunk_to_result(db, chunk, 0.0) for chunk in recent]

    @staticmethod
    def _cosine_similarity(left: list[float], right: list[float]) -> float:
        dot = sum(a * b for a, b in zip(left, right))
        norm_left = math.sqrt(sum(a * a for a in left))
        norm_right = math.sqrt(sum(b * b for b in right))
        if norm_left == 0 or norm_right == 0:
            return 0.0
        return dot / (norm_left * norm_right)

    def _chunk_to_result(
        self, db: Session, chunk: DocumentChunk, similarity: float
    ) -> dict[str, Any]:
        attachment = db.get(Attachment, chunk.attachment_id)
        return {
            "attachment_id": chunk.attachment_id,
            "chunk_index": chunk.chunk_index,
            "content": chunk.content,
            "similarity": float(similarity),
            "file_name": attachment.file_name
            if attachment is not None
            else "documento",
        }

    def retrieve_for_attachment(
        self,
        db: Session,
        attachment_id: int,
        user_id: int,
        query: str,
        top_k: int = DEFAULT_TOP_K,
    ) -> list[dict[str, Any]]:
        """Retrieve chunks for one attachment after verifying project ownership."""
        attachment = db.get(Attachment, attachment_id)
        if attachment is None:
            raise HTTPException(status_code=404, detail="Documento no encontrado")

        project_id = self.resolve_project_id(db, attachment)
        if project_id is None:
            raise HTTPException(
                status_code=404, detail="Proyecto del documento no encontrado"
            )

        project = db.get(Project, project_id)
        if (
            project is None
            or project.owner_id != user_id
            or project.deleted_at is not None
        ):
            raise HTTPException(
                status_code=403,
                detail="No tiene permisos para acceder a este documento",
            )

        return self.retrieve_context(
            db,
            project_id=project_id,
            query=query,
            top_k=top_k,
            attachment_id=attachment_id,
        )

    # --------------------------------------------------------------- formatting
    def format_rag_context(self, chunks: list[dict[str, Any]]) -> str | None:
        """Render retrieved chunks into a bounded prompt section."""
        if not chunks:
            return None

        parts: list[str] = []
        for index, chunk in enumerate(chunks, start=1):
            similarity = float(chunk.get("similarity", 0.0))
            parts.append(
                f"[Fragmento {index} | {chunk.get('file_name', 'documento')} | "
                f"chunk {chunk.get('chunk_index', 0)} | "
                f"similitud {similarity:.2f}]\n{chunk.get('content', '')}"
            )

        return truncate_context("\n\n".join(parts), RAG_CONTEXT_MAX_CHARS)


